/** Model selection is captured before route preparation and remains stable within a step. */
import { afterEach, describe, expect, it } from 'vitest'
import { Context } from '@deepseek-ai/cordis'
import { agentEvents, installModelSelection, type Agent, type ModelSelection, type ModelSelectionRef } from '../src/index.ts'
import { createUserMessage, ReasoningEffortId, type LlmCallConfig } from '@deepseek-ai/dsh-llm'
import { Session, SessionId } from '@deepseek-ai/dsh-session'

const contexts: Context[] = []
afterEach(async () => {
  for (const ctx of contexts.splice(0)) await ctx.fiber.dispose()
})
const signal = new AbortController().signal
const input = createUserMessage({ content: [{ type: 'text', text: 'continue' }], source: { kind: 'user' } })

function harness(current?: ModelSelection, previous?: ModelSelection) {
  const ctx = new Context()
  contexts.push(ctx)
  const selection: ModelSelectionRef = { current, assembled: undefined }
  const dispose = installModelSelection(ctx, selection)
  let route: LlmCallConfig = { provider: 'seed', model: 'seed', temperature: 0.2 }
  const agent = { session: Session.create(SessionId('model-selection')), currentRoute: () => route } as Agent
  if (previous) agent.session.append('request/header', { header: { config: previous }, reason: 'initial' })
  const request = async (step: number, seed: LlmCallConfig = { provider: 'seed', model: 'seed', temperature: 0.2 }) => {
    route = await agentEvents(ctx, agent).waterfall('agent/request', { turn: 1, step, signal }, () => Promise.resolve(seed))
    return route
  }
  const preStep = (messages = [input], offered = [input], step = 1, requestSignal = signal) =>
    agentEvents(ctx, agent).waterfall('agent/pre-step', { turn: 1, step, messages: offered, signal: requestSignal },
      () => Promise.resolve({ kind: 'enter' as const, messages }))
  return { ctx, agent, selection, dispose, request, preStep }
}

function notice(from: string, to: string) {
  return { content: [{ type: 'text', text: `[model changed: assistant turns above this point were generated by ${from}; the session continues with ${to}]` }] }
}

describe('installModelSelection()', () => {
  it('captures selection per step, preserves retries, and disposes routing', async () => {
    const h = harness()
    const seed: LlmCallConfig = { provider: 'seed', model: 'seed', temperature: 0.2 }
    expect(await h.request(0, seed)).toBe(seed)
    h.selection.current = { provider: 'alpha', model: 'a1', reasoningEffort: ReasoningEffortId('high') }
    expect(await h.request(1)).toEqual({ ...seed, ...h.selection.current })
    h.selection.current = { provider: 'beta', model: 'b1' }
    expect(await h.request(1)).toMatchObject({ provider: 'alpha', model: 'a1' })
    expect(await h.request(2, { ...seed, reasoningEffort: ReasoningEffortId('max') })).toEqual({ ...seed, ...h.selection.current })
    h.dispose()
    expect(await h.request(3, seed)).toBe(seed)
  })

  it('announces the bound same-provider and cross-provider routes', async () => {
    const h = harness({ provider: 'alpha', model: 'a1' }, { provider: 'alpha', model: 'a0' })
    await h.request(1)
    await expect(h.preStep()).resolves.toMatchObject({ messages: [input, notice('a0', 'a1')] })
    h.selection.current = { provider: 'beta', model: 'b1' }
    await h.request(2)
    h.selection.current = { provider: 'alpha', model: 'a2' }
    await expect(h.preStep()).resolves.toMatchObject({ messages: [input, notice('alpha/a0', 'beta/b1')] })
    await h.request(3)
    await expect(h.preStep()).resolves.toMatchObject({ messages: [input, notice('a0', 'a2')] })
  })

  it('preserves initial, unchanged, rejected, cancelled, and disposed decisions', async () => {
    const h = harness({ provider: 'alpha', model: 'a0' })
    await h.request(1)
    await expect(h.preStep()).resolves.toEqual({ kind: 'enter', messages: [input] })
    h.agent.session.append('request/header', { header: { config: h.agent.currentRoute() }, reason: 'initial' })
    h.selection.current = { provider: 'alpha', model: 'a0', reasoningEffort: ReasoningEffortId('high') }
    await h.request(2)
    await expect(h.preStep()).resolves.toEqual({ kind: 'enter', messages: [input] })
    h.selection.current = { provider: 'alpha', model: 'a1' }
    await h.request(3)
    await expect(agentEvents(h.ctx, h.agent).waterfall('agent/pre-step', { turn: 1, step: 3, messages: [], signal },
      () => Promise.resolve({ kind: 'reject' as const }))).resolves.toEqual({ kind: 'reject' })
    const aborted = AbortSignal.abort()
    await expect(h.preStep([input], [input], 3, aborted)).resolves.toEqual({ kind: 'enter', messages: [input] })
    h.dispose()
    await expect(h.preStep()).resolves.toEqual({ kind: 'enter', messages: [input] })
  })

  it('preserves empty claims and announces an empty tool continuation', async () => {
    const h = harness({ provider: 'alpha', model: 'a1' }, { provider: 'alpha', model: 'a0' })
    await h.request(1)
    await expect(h.preStep([])).resolves.toEqual({ kind: 'enter', messages: [] })
    await expect(h.preStep([], [input], 2)).resolves.toEqual({ kind: 'enter', messages: [] })
    await expect(h.preStep([], [], 2)).resolves.toMatchObject({ messages: [notice('a0', 'a1')] })
  })
})
